#!/usr/bin/env python3
"""The lightning-bolt earring's circuit: simple_earring's (vendored at 7a83b33), with the LED field
from this board's geometry.

Everything but the LEDs is simple_earring's rev-2 circuit unchanged: RP2350A + W25Q16JV, the
LGS4056H charger at 50 mA, the VBUS/cell power path, the NCP730 LDO, the B3U power button with
its CPU-held latch and one-button BOOTSEL, three TPS22913 zone switches with their level
shifters, the LSM6DS3TR-C IMU, the ALS-PT19 light sensor, USB-C with ESD.

The LEDs are geometry.json's, numbered in chain order ring by ring. The three zones keep
simple_earring's net names: L is ring 0 (outermost), R is ring 1, C is rings 2 and up, chained
from the outside in. One 100 nF bypass per BYPASS_EVERY LEDs of a zone, numbered from C201; they sit on the
back between a ring's two rail vias.

    circuit.py [--geometry geometry.json] [-o circuit.json]
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "vendor/simple_earring/scripts"))
import circuit as se  # noqa: E402

BYPASS_EVERY = 6     # with the In1 GND / In2 VLED plane pair under every zone, and 10 uF at each zone switch
CHARGE_MA = 50     # R_PROG 18k: 0.5 C for a ~100 mAh 401030 / 501030-class cell


def zones_from(geometry):
    """Zone -> LED numbers (1-based, geometry order) in chain order."""
    out = {"L": [], "R": [], "C": []}
    for i, d in enumerate(geometry["leds"], 1):
        out["L" if d["ring"] == 0 else "R" if d["ring"] == 1 else "C"].append(i)
    return out


def build(geometry):
    zones = zones_from(geometry)
    n = len(geometry["leds"])
    se.led_zones = lambda design: zones
    se.led_zone_of = lambda design: {i: z for z, chain in zones.items() for i in chain}
    # The vendored bypass loop numbers caps C30 + LED index, which collides with its own C75..C79
    # past 45 LEDs: it is given a step no LED reaches (so it adds only C30, on LED1's zone), and
    # this board's bypasses are numbered from C201.
    design = {"leds": {"count": n, "bypass_every": 10 ** 6}, "power": {"charge_current_ma": CHARGE_MA}}
    se.ROOT = HERE.parent / "vendor/simple_earring"
    c = se.build_circuit(design)
    zone_of = se.led_zone_of(design)
    k = 201
    for z, chain in zones.items():
        for j in range(BYPASS_EVERY // 2, len(chain), BYPASS_EVERY):
            c.add(f"C{k}", "c_100n", "100n", {1: f"VLED_{z}", 2: "GND"})
            k += 1
    for comp in c.components.values():
        if not comp.footprint:
            p = se.load_parts()[comp.part]
            comp.footprint, comp.lcsc = p["footprint"], p.get("lcsc", "")
    return c, zones


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--geometry", default=str(HERE.parent / "geometry.json"))
    ap.add_argument("-o", "--output", default=str(HERE.parent / "circuit.json"))
    a = ap.parse_args()
    g = json.load(open(a.geometry))
    c, zones = build(g)
    parts = se.load_parts()
    comps = {}
    for ref, comp in sorted(c.components.items()):
        p = parts[comp.part]
        comps[ref] = {"part": comp.part, "value": comp.value, "footprint": comp.footprint, "lcsc": comp.lcsc or "", "mpn": p.get("mpn") or "", "pins": comp.pins}
    nets = {k: [f"{r}.{p}" for r, p in v] for k, v in sorted(c.nets.items())}
    json.dump({"note": "Generated by scripts/circuit.py from simple_earring's circuit (vendored) and geometry.json.", "zones": zones, "components": comps, "nets": nets}, open(a.output, "w"), indent=1)
    print(json.dumps({"components": len(comps), "nets": len(nets), "leds": len(g["leds"]), "zones": {z: len(v) for z, v in zones.items()}}))


if __name__ == "__main__":
    main()
